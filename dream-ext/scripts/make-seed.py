#!/usr/bin/env python3
"""
Makes dream-ext/src/level-seed.ts from the learner's vocabulary.json (the file My tutor's helper writes).

    python3 dream-ext/scripts/make-seed.py "<path to>/vocabulary.json" ["<path to>/not-in-app.txt"]

Only the words go in: each word or phrase, the day it got its status, and its level group when it has one.
Left out on purpose:
- the example sentences and the Level Check tests (their titles);
- every item of the second file, one per line (a private list, kept next to vocabulary.json, not in this repo);
- single words still being learned that are very common (Zipf 4.8 or more, the line the app itself uses for "easy
  whatever its level"): a slip of the tap, not words to learn, and they would make easy sentences stop.
The phrases themselves stay, and some are quotes from what was read.
Before it writes, it prints the items with a capital letter, to look over.
"""
import json, sys, os, gzip, collections

here = os.path.dirname(os.path.abspath(__file__))
src = sys.argv[1]
doc = json.load(open(src, encoding='utf-8'))
out = os.path.join(here, '..', 'src', 'level-seed.ts')

skip = set()
if len(sys.argv) > 2:
    for line in open(sys.argv[2], encoding='utf-8'):
        line = ' '.join(line.split()).lower()
        if line and not line.startswith('#'):
            skip.add(line)

zipf = {}
for z, words in json.load(gzip.open(os.path.join(here, '..', '..', 'youtube-to-claude', 'dream', 'zipf.json.gz'))).items():
    for w in words.split(' '):
        zipf[w] = int(z) / 10
COMMON = 4.8

def freq(word):
    """how common a word is, as its most common simple form ("wears" -> "wear", "matched" -> "match")"""
    w = word.lower()
    forms = [w]
    if w.endswith('s'): forms.append(w[:-1])
    if w.endswith('es'): forms.append(w[:-2])
    if w.endswith('ed'): forms += [w[:-2], w[:-1]]
    # (not "-ing" or "-ly": "courting", "standing" as a noun, "openly" are often learned for their own meaning)
    # (a stem of 4 letters or more: "bed" from "beds" is not "be")
    return max([zipf.get(w, 0)] + [zipf.get(f, 0) for f in forms[1:] if len(f) >= 4])

def clean(item):
    item = ' '.join(str(item).split())
    if not item or '|' in item or len(item) > 80:
        raise SystemExit(f'cannot take this item: {item!r}')
    return item

# every word once: known wins over still learning, and of two entries of one word the earlier day stays
seen = set()
left = collections.Counter()
known = collections.defaultdict(list)
for x in sorted(doc.get('known', []), key=lambda x: x.get('date') or ''):
    item = clean(x['item'])
    if item.lower() in seen:
        continue
    if item.lower() in skip:
        left['on the private list'] += 1
        continue
    seen.add(item.lower())
    known[x.get('date') or ''].append(item)
learning = collections.defaultdict(list)
common = []
for x in sorted(doc.get('stillLearning', []), key=lambda x: x.get('date') or ''):
    item = clean(x['item'])
    if item.lower() in seen:
        continue
    if item.lower() in skip:
        left['on the private list'] += 1
        continue
    if item.isalpha() and freq(item) >= COMMON:
        common.append(item)
        continue
    seen.add(item.lower())
    g = x.get('group') if x.get('group') in ('b2', 'c1', 'c2') else ''
    learning[(x.get('date') or '', g)].append(item)

nk = sum(len(v) for v in known.values())
nl = sum(len(v) for v in learning.values())
caps = sorted({w for v in list(known.values()) + list(learning.values()) for w in v if w[:1].isupper()})
print('items with a capital letter (look them over):', ', '.join(caps))
print('left out as very common:', ', '.join(common))
print('left out from the private list:', left['on the private list'])

def q(s):
    return json.dumps(s, ensure_ascii=False)

lines = [
    '/**',
    " * GENERATED by scripts/make-seed.py from the learner's vocabulary.json. Do not edit by hand.",
    " * The learner's own words, built into the app at their request so a new install starts with them:",
    f' * {nk} known, {nl} still learning. Words and phrases only: no example sentences and no test titles;',
    " * the items of the learner's private list and very common single words are left out.",
    ' */',
    f'export const SEED_MADE = {q((doc.get("updatedAt") or "")[:10])};',
    f'export const SEED_LEVEL = {q(doc.get("currentLevel") or "")};',
    '/** [the day they were marked known, the words joined by "|"] */',
    'export const SEED_KNOWN: [string, string][] = [',
]
for d in sorted(known):
    lines.append(f'  [{q(d)}, {q("|".join(sorted(known[d], key=str.lower)))}],')
lines.append('];')
lines.append('/** [the day, the level group ("" = none), the words joined by "|"] */')
lines.append("export const SEED_LEARNING: [string, '' | 'b2' | 'c1' | 'c2', string][] = [")
for d, g in sorted(learning):
    lines.append(f'  [{q(d)}, {q(g)}, {q("|".join(sorted(learning[(d, g)], key=str.lower)))}],')
lines.append('];')
open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('wrote', os.path.normpath(out), 'known', nk, 'learning', nl)
