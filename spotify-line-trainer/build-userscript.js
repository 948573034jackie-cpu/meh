// Bundles the extension sources into one userscript for Safari on iPad/iPhone
// (Userscripts app) or Tampermonkey. Run: node build-userscript.js
const fs = require('fs');
const path = require('path');
const read = f => fs.readFileSync(path.join(__dirname, f), 'utf8');
const version = JSON.parse(read('manifest.json')).version;
const header = `// ==UserScript==
// @name         Spotify Line Trainer
// @namespace    https://github.com/948573034jackie-cpu/meh
// @version      ${version}
// @description  Loop every lyric line of a Spotify song N times at the speed you choose, or run the slow-to-fast training ladder.
// @match        https://open.spotify.com/*
// @run-at       document-start
// @inject-into  page
// @grant        none
// @updateURL    https://raw.githubusercontent.com/948573034jackie-cpu/meh/spotify-line-trainer/spotify-line-trainer/dist/spotify-line-trainer.user.js
// @downloadURL  https://raw.githubusercontent.com/948573034jackie-cpu/meh/spotify-line-trainer/spotify-line-trainer/dist/spotify-line-trainer.user.js
// ==/UserScript==
// Generated by build-userscript.js from src/ — edit the sources, not this file.
`;
const body = ['src/core.js', 'src/page.js', 'src/ui.js'].map(f => `// ---- ${f} ----\n${read(f)}`).join('\n');
fs.mkdirSync(path.join(__dirname, 'dist'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'dist/spotify-line-trainer.user.js'), header + body);
console.log('wrote dist/spotify-line-trainer.user.js');
