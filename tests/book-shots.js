// screenshots of I Know Book in WebKit (iPhone 13), for looking at the design: node tests/book-shots.js <out dir>
const fs = require('fs'); const path = require('path'); const http = require('http');
const H = require('./ios-harness');
const { pw, IOS, MIME, until, sleep, source, sheetScripts, stores, keychain } = H;
const OUT = process.argv[2] || '.';
const PORT = +process.env.BOOK_PAGES_PORT || 8817;
H.watchdog(4); H.startServer();
(async () => {
  const browser = await pw.webkit.launch();
  http.createServer((q, r) => { const f = path.join(IOS, 'Web/dream', path.basename(q.url.split('?')[0])); if (!fs.existsSync(f)) { r.writeHead(404); return r.end(); } r.writeHead(200, { 'content-type': MIME[path.extname(f)] || 'text/plain' }); r.end(fs.readFileSync(f)); }).listen(PORT);
  for (const k of Object.keys(stores.local)) delete stores.local[k];
  Object.assign(stores.local, { drLevel: { tests: [], currentLevel: '', log: {}, seeded: 99 }, drExtras: { tutorOn: true, fakeVoice: true, phoneSet: true, myLevel: 50, migrated: 9 }, drSettings: { learnerLevel: 'B2', listen: { commandWindowMs: 2500 } }, drVocab: { words: {}, marked: {} } });
  keychain.drKeys = JSON.stringify({ anthropic: 'sk-ant-test-key' });
  const ctx = await H.newAppContext(browser, 'iPhone 13', { device: 'phone' });
  const p = await ctx.newPage();
  p.on('pageerror', (e) => console.log('PAGE ERROR', String(e.message || e).slice(0, 300)));
  p.on('console', (m) => { if (m.type() === 'error') console.log('console error:', m.text().slice(0, 200)); });
  await p.addInitScript({ content: source(sheetScripts) });
  await p.goto(`http://localhost:${PORT}/book.html`);
  await until(() => p.evaluate(() => document.body.dataset.ready === '1'), 15000);
  const shot = async (name) => { await sleep(350); await p.screenshot({ path: path.join(OUT, `${name}.png`) }); console.log('shot', name); };
  const dbg = () => p.evaluate(() => { try { return JSON.parse(document.documentElement.dataset.drDebug || 'null'); } catch (e) { return null; } });
  await shot('1-empty');
  await p.evaluate(() => document.getElementById('e-sample').click());
  await until(async () => { const d = await dbg(); return d && d.open && d.sentences > 5 ? d : null; }, 20000);
  await shot('2-open-with-bars');
  await sleep(2800);
  await shot('3-reading');
  console.log(JSON.stringify(await dbg()).slice(0, 500));
  await p.evaluate(() => window.__iknowBook.turn(1));
  await shot('4-page-2');
  await p.evaluate(() => document.getElementById('b-look').click());
  await shot('5-look-sheet');
  await p.evaluate(() => document.querySelector('.sw[data-theme="night"]').click());
  await shot('6-night');
  await p.evaluate(() => { document.getElementById('veil').click(); document.getElementById('b-tutor').click(); });
  await shot('7-tutor-sheet');
  await p.evaluate(() => document.getElementById('veil').click());
  await p.evaluate(() => { const w = [...document.querySelectorAll('#flow .w')].find((x) => x.textContent === 'attached' || x.textContent === 'ridiculous') || document.querySelector('#flow .w.hard'); window.__w = w && w.textContent; });
  const box = await p.evaluate(() => { const w = [...document.querySelectorAll('#flow .w.hard')].find((x) => { const r = x.getBoundingClientRect(); return r.left > 0 && r.left < innerWidth; }); if (!w) return null; const r = w.getBoundingClientRect(); return [r.left + r.width / 2, r.top + r.height / 2, w.textContent]; });
  console.log('hard word', JSON.stringify(box));
  if (box) { await p.touchscreen.tap(box[0], box[1]); await sleep(500); await shot('8-card'); }
  await sleep(4000);
  await p.evaluate(() => window.__iknowBook.play(true));
  await sleep(900);
  await shot('8b-listening');
  await p.evaluate(() => window.__iknowBook.play(false));
  await p.evaluate(() => { const t = document.querySelector('.sw[data-theme="paper"]'); });
  await p.evaluate(() => document.getElementById('b-lib').click());
  await sleep(600);
  await shot('9-library');
  await browser.close(); process.exit(0);
})().catch((e) => { console.log('crashed', e && e.stack || e); process.exit(1); });
